"""Lab secrets: materialize *-secret.yaml from *-secret.yaml.example.

Purpose
    A lab overlay must come up without anyone typing passwords. Example files
    may hold placeholders that are replaced by random values, generated once
    per overlay and kept in env/<overlay>/lab-secrets.yml (gitignored), so the
    same name yields the same value in every file (e.g. an S3 key written in
    the provider Secret and in the consumer Secret).

Placeholders (inside *-secret.yaml.example)
    <lab:NAME>            random value, 32 chars [A-Za-z0-9]
    <lab:NAME:20>         same, with an explicit length
    <lab-htpasswd:NAME>   {SHA} hash of the value NAME (nginx/Apache htpasswd)

Behaviour
    An existing *-secret.yaml is never overwritten (it may hold real
    credentials). Examples without placeholders need manual input and are only
    reported.

Related
    app/secrets/sealer.py (sealing), role 04_deploy_k8s tasks/seal.yml
"""

from __future__ import annotations

import base64
import hashlib
import re
import secrets
import string
from dataclasses import dataclass
from pathlib import Path

import yaml

EXAMPLE_SUFFIX = '.example'
STORE_FILE = 'lab-secrets.yml'
DEFAULT_LENGTH = 32
_ALPHABET = string.ascii_letters + string.digits
_PLACEHOLDER_RE = re.compile(
    r'<(?P<kind>lab|lab-htpasswd):(?P<name>[A-Za-z0-9_.-]+)'
    r'(?::(?P<length>\d+))?>'
)
_STORE_MODE = 0o600

STATUS_GENERATED = 'generated'
STATUS_PRESENT = 'present'
STATUS_MANUAL = 'manual'


@dataclass(frozen=True)
class SecretFile:
    example: Path
    target: Path
    status: str


class LabSecretStore:
    """Named random values of one overlay (env/<overlay>/lab-secrets.yml)."""

    def __init__(self, path: Path) -> None:
        self.path = path
        self.values: dict[str, str] = {}
        if path.is_file():
            data = yaml.safe_load(path.read_text(encoding='utf-8')) or {}
            self.values = {str(k): str(v) for k, v in data.items()}
        self._dirty = False

    def get(self, name: str, length: int = DEFAULT_LENGTH) -> str:
        if name not in self.values:
            self.values[name] = _random_value(length)
            self._dirty = True
        return self.values[name]

    def save(self) -> None:
        if not self._dirty:
            return
        self.path.parent.mkdir(parents=True, exist_ok=True)
        header = (
            '# Lab secret values of this overlay — generated by\n'
            '# `k8s-blueprint secrets init`. Local only (env/ is gitignored).\n'
        )
        self.path.write_text(
            header + yaml.safe_dump(dict(sorted(self.values.items()))),
            encoding='utf-8',
        )
        self.path.chmod(_STORE_MODE)
        self._dirty = False


def _random_value(length: int) -> str:
    """Random [A-Za-z0-9] value with upper, lower and digit when it fits.

    Password policies (e.g. Harbor) require the three classes.
    """
    classes = (string.ascii_lowercase, string.ascii_uppercase, string.digits)
    while True:
        value = ''.join(secrets.choice(_ALPHABET) for _ in range(length))
        if length < len(classes) or all(
            any(char in group for char in value) for group in classes
        ):
            return value


def htpasswd_sha(password: str) -> str:
    digest = hashlib.sha1(password.encode('utf-8')).digest()  # noqa: S324
    return '{SHA}' + base64.b64encode(digest).decode('ascii')


def has_placeholders(text: str) -> bool:
    return bool(_PLACEHOLDER_RE.search(text))


def render(text: str, store: LabSecretStore) -> str:
    def replace(match: re.Match[str]) -> str:
        length = int(match['length'] or DEFAULT_LENGTH)
        value = store.get(match['name'], length)
        if match['kind'] == 'lab-htpasswd':
            return htpasswd_sha(value)
        return value

    return _PLACEHOLDER_RE.sub(replace, text)


def example_files(repo_root: Path, overlay_id: str) -> list[Path]:
    """Repo-relative *-secret.yaml.example files of one overlay."""
    root = repo_root / 'k8s'
    return sorted(
        path.relative_to(repo_root)
        for path in root.glob(
            f'**/overlays/{overlay_id}/**/*-secret.yaml{EXAMPLE_SUFFIX}'
        )
    )


def store_path(repo_root: Path, overlay_id: str) -> Path:
    return repo_root / 'env' / overlay_id / STORE_FILE


def init_overlay(
    repo_root: Path,
    overlay_id: str,
    *,
    dry_run: bool = False,
) -> list[SecretFile]:
    """Create the missing *-secret.yaml files that can be generated."""
    store = LabSecretStore(store_path(repo_root, overlay_id))
    results: list[SecretFile] = []
    for example in example_files(repo_root, overlay_id):
        target = example.with_name(example.name.removesuffix(EXAMPLE_SUFFIX))
        if (repo_root / target).exists():
            results.append(SecretFile(example, target, STATUS_PRESENT))
            continue
        text = (repo_root / example).read_text(encoding='utf-8')
        if not has_placeholders(text):
            results.append(SecretFile(example, target, STATUS_MANUAL))
            continue
        if not dry_run:
            (repo_root / target).write_text(
                render(text, store), encoding='utf-8'
            )
            (repo_root / target).chmod(_STORE_MODE)
        results.append(SecretFile(example, target, STATUS_GENERATED))
    if not dry_run:
        store.save()
    return results
